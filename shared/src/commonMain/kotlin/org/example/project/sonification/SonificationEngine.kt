package org.example.project.sonification

import org.example.project.model.SpectralClass
import org.example.project.model.Star
import kotlin.math.*

// ─── Audio parameters produced by the engine ───────────────────

/**
 * Which waveform shape to use.
 * Hot stars get harmonically rich shapes; cool stars get soft ones.
 */
enum class WaveShape { SINE, TRIANGLE, SQUARE, SAWTOOTH }

/**
 * ADSR envelope times in seconds.
 */
data class Envelope(
    val attack: Float  = 0.08f,
    val decay: Float   = 0.15f,
    val sustain: Float = 0.6f,   // sustain *level* (0‒1)
    val release: Float = 0.4f
)

/**
 * Complete set of audio parameters for one star.
 * Generated by [SonificationEngine.parameterize], consumed by [WaveformRenderer].
 */
data class StarSound(
    val star: Star,
    val fundamentalHz: Float,
    val amplitude: Float,          // 0‒1
    val waveShape: WaveShape,
    val harmonics: List<Harmonic>,  // overtones
    val envelope: Envelope,
    val durationSec: Float          // total note length including release
)

data class Harmonic(
    val multiplier: Int,   // frequency = fundamental * multiplier
    val amplitude: Float   // relative to fundamental (0‒1)
)

// ─── Engine ────────────────────────────────────────────────────

object SonificationEngine {

    // Musical range: G3 (~196 Hz) to F#6 (~1480 Hz).
    // The floor is kept above the roll-off of phone/laptop speakers so even the
    // coolest stars are clearly audible; the ceiling tames the piercing top end.
    private const val MIDI_LOW  = 55   // G3  (~196 Hz)
    private const val MIDI_HIGH = 90   // F#6 (~1480 Hz)
    private const val TEMP_LOW  = 2400.0
    private const val TEMP_HIGH = 50000.0

    // Luminosity range for amplitude mapping
    private const val LUM_LOW  = 0.5
    private const val LUM_HIGH = 200000.0

    // Duration range (seconds)
    private const val DUR_SHORT = 2.0f
    private const val DUR_LONG  = 5.0f

    /**
     * Map a [Star]'s physical properties to audio parameters.
     *
     * Mapping rationale:
     *  • Temperature  → pitch (hotter = higher, logarithmic)
     *  • Spectral class → waveform timbre
     *  • Luminosity   → amplitude / loudness
     *  • Radius       → note duration (bigger = longer sustain)
     */
    fun parameterize(star: Star): StarSound {
        val freq = temperatureToFrequency(star.temperatureK)
        val amp  = luminosityToAmplitude(star.luminositySolar)
        val (shape, harmonics) = spectralToTimbre(star.spectralClass)
        val dur  = radiusToDuration(star.radiusSolar)
        val env  = buildEnvelope(star)

        return StarSound(
            star = star,
            fundamentalHz = freq,
            amplitude = amp,
            waveShape = shape,
            harmonics = harmonics,
            envelope = env,
            durationSec = dur
        )
    }

    // ── Mapping functions ──────────────────────────────────────

    /**
     * Logarithmic mapping from temperature (K) to frequency (Hz).
     * Quantized to the nearest semitone for musical coherence.
     */
    private fun temperatureToFrequency(tempK: Int): Float {
        val t = tempK.toDouble().coerceIn(TEMP_LOW, TEMP_HIGH)
        val fraction = (ln(t) - ln(TEMP_LOW)) / (ln(TEMP_HIGH) - ln(TEMP_LOW))
        val midiNote = MIDI_LOW + fraction * (MIDI_HIGH - MIDI_LOW)

        // Quantize to nearest semitone
        val quantized = midiNote.roundToInt()

        // MIDI note → Hz:  f = 440 × 2^((n-69)/12)
        return (440.0 * 2.0.pow((quantized - 69) / 12.0)).toFloat()
    }

    /**
     * Spectral class determines waveform shape and harmonic profile.
     *
     *  O/B (hot, energetic)  → square wave, strong odd harmonics
     *  A   (brilliant white) → sawtooth, moderate harmonics
     *  F   (warm white)      → triangle, gentle harmonics
     *  G   (sun-like)        → sine + light harmonics (warm, pure)
     *  K   (orange)          → triangle, very soft
     *  M   (red, cool)       → sine, almost no harmonics (deep hum)
     */
    private fun spectralToTimbre(sc: SpectralClass): Pair<WaveShape, List<Harmonic>> =
        when (sc) {
            SpectralClass.O -> WaveShape.SQUARE to listOf(
                Harmonic(3, 0.33f), Harmonic(5, 0.20f), Harmonic(7, 0.14f)
            )
            SpectralClass.B -> WaveShape.SQUARE to listOf(
                Harmonic(3, 0.28f), Harmonic(5, 0.15f)
            )
            SpectralClass.A -> WaveShape.SAWTOOTH to listOf(
                Harmonic(2, 0.25f), Harmonic(3, 0.15f), Harmonic(4, 0.08f)
            )
            SpectralClass.F -> WaveShape.TRIANGLE to listOf(
                Harmonic(3, 0.11f), Harmonic(5, 0.04f)
            )
            SpectralClass.G -> WaveShape.SINE to listOf(
                Harmonic(2, 0.12f), Harmonic(3, 0.06f)
            )
            SpectralClass.K -> WaveShape.TRIANGLE to listOf(
                Harmonic(3, 0.06f)
            )
            SpectralClass.M -> WaveShape.SINE to listOf(
                Harmonic(2, 0.05f)
            )
        }

    /**
     * Logarithmic mapping from luminosity to playback amplitude.
     * Capped to avoid clipping; even faint stars are audible.
     */
    private fun luminosityToAmplitude(lumSolar: Double): Float {
        val l = lumSolar.coerceIn(LUM_LOW, LUM_HIGH)
        val fraction = (ln(l) - ln(LUM_LOW)) / (ln(LUM_HIGH) - ln(LUM_LOW))
        return (0.25f + 0.55f * fraction.toFloat()).coerceIn(0.25f, 0.80f)
    }

    /**
     * Bigger stars sustain longer.
     * Log scale: Sun (1 R☉) → ~2 s, Betelgeuse (887 R☉) → ~5 s.
     */
    private fun radiusToDuration(radiusSolar: Double): Float {
        val r = radiusSolar.coerceIn(0.5, 1000.0)
        val fraction = (ln(r) - ln(0.5)) / (ln(1000.0) - ln(0.5))
        return DUR_SHORT + (DUR_LONG - DUR_SHORT) * fraction.toFloat()
    }

    /**
     * Build an ADSR envelope tuned to the star's character.
     * Supergiants have slow attacks; dwarfs snap in quickly.
     */
    private fun buildEnvelope(star: Star): Envelope {
        val isGiant = star.radiusSolar > 20
        return Envelope(
            attack  = if (isGiant) 0.25f else 0.06f,
            decay   = if (isGiant) 0.3f  else 0.12f,
            sustain = if (isGiant) 0.5f  else 0.7f,
            release = if (isGiant) 0.8f  else 0.3f
        )
    }
}
